static boolean rasterizer_environment_fog_screen_is_active(
	void)
{
	short window_index = global_window_parameters.window_index;
	boolean active;

	if (VALID_INDEX(window_index, MAXIMUM_WINDOWS))
	{
		struct fog_screen const *screen;

		fog_screen_active[window_index] = FALSE;
		if (rasterizer_globals.fps_accumulation_frame_index !=
			last_frame_index[window_index])
		{
			match_assert(
				"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
				92,
				global_window_parameters.fog.planar_maximum_depth!=0.0f);
			if (rasterizer_debug_options.drawing_mode == _rasterizer_drawing_mode_normal &&
				rasterizer_debug_options.draw_environment_fog_screen &&
				global_window_parameters.rasterizer_target == _rasterizer_target_render_primary &&
				(screen = global_window_parameters.fog.screen) != NULL &&
				screen->layer_count > 0 &&
				screen->map.index != NONE &&
				screen->far_distance != 0.0f &&
				screen->far_density != 0.0f &&
				(!TEST_FLAG(
					global_window_parameters.fog.runtime_flags,
					_fog_screen_use_fixed_density_bit) ||
					global_window_parameters.fog.screen_external_intensity > 0.0f))
			{
				real depth = global_window_parameters.fog.planar_maximum_depth;
				real distance =
					global_window_parameters.camera.position.x *
						global_window_parameters.fog.plane.n.i +
					global_window_parameters.camera.position.y *
						global_window_parameters.fog.plane.n.j +
					global_window_parameters.camera.position.z *
						global_window_parameters.fog.plane.n.k -
					global_window_parameters.fog.plane.d;
				real z = screen->start_distance_from_fog_plane;
				real base_z = -depth;

				if (z == base_z)
					z = 0.0001f - depth;
				local_fog_eye_density = TEST_FLAG(
					global_window_parameters.fog.runtime_flags,
					_fog_screen_use_fixed_density_bit)
						? global_window_parameters.fog.screen_external_intensity
						: PIN((distance - z) / (base_z - z), 0.0f, 1.0f);
				if (local_fog_eye_density > 0.0f)
					fog_screen_active[window_index] = TRUE;
			}
		}
		active = fog_screen_active[window_index];
	}
	else
	{
		active = FALSE;
	}

	return active;
}

void _rasterizer_environment_fog_screen_wind_get_vector(
	short window_index,
	real dt,
	real_vector3d *wind_vector)
{
	struct rasterizer_environment_fog_screen_wind *wind =
		&windows[window_index].wind;

	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		484,
		window_index>=0 && window_index<MAXIMUM_WINDOWS);
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		485,
		wind_vector);

	wind_vector->i = wind->magnitude * wind->direction.i * dt;
	wind_vector->j = wind->direction.j * wind->magnitude * dt;
	wind_vector->k = 0.0f;

	return;
}

static void rasterizer_environment_fog_screen_wind_update(
	struct fog_screen const *screen,
	struct rasterizer_environment_fog_screen_wind *wind)
{
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		163,
		screen);
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		164,
		wind);

	if (screen->wind_velocity.upper > 0.0f)
	{
		real_vector2d *target_direction = &wind->target_direction;
		real weight = 1.0f - screen->wind_acceleration_weight;
		real acceleration_weight;

		wind->direction.i *= weight;
		wind->direction.j *= weight;
		acceleration_weight = screen->wind_acceleration_weight;
		wind->direction.i += target_direction->i * acceleration_weight;
		wind->direction.j += target_direction->j * acceleration_weight;
		if (normalize2d(&wind->direction) == 0.0f)
		{
			wind->direction.i = 1.0f;
			wind->direction.j = 0.0f;
		}
		scalars_interpolate(
			wind->magnitude,
			wind->target_magnitude,
			screen->wind_acceleration_weight,
			&wind->magnitude);
		if (global_frame_parameters.game_time_sec - wind->change_time >= wind->change_period)
		{
			real_vector2d perpendicular;
			real random_fraction = real_local_random();
			real weight;
			real sign;
			real scale;

			weight = (real)pow(
				random_fraction,
				1.0f - screen->wind_perpendicular_weight);
			sign = local_random_boolean() ? -1.0f : 1.0f;
			perpendicular2d(&wind->direction, &perpendicular);
			scale = sign * weight;
			perpendicular.i *= scale;
			perpendicular.j *= scale;
			target_direction->i = wind->direction.i * (1.0f - weight) + perpendicular.i;
			target_direction->j = wind->direction.j * (1.0f - weight) + perpendicular.j;
			if (normalize2d(target_direction) == 0.0f)
			{
				target_direction->i = 1.0f;
				target_direction->j = 0.0f;
			}
			wind->target_magnitude = real_local_random_range(
				screen->wind_velocity.lower,
				screen->wind_velocity.upper);
			wind->change_time = global_frame_parameters.game_time_sec;
			wind->change_period = real_local_random_range(
				screen->wind_period.lower,
				screen->wind_period.upper);
		}
	}

	return;
}

void _rasterizer_environment_fog_screen_begin(
	short pass)
{
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		499,
		pass==0 || pass==1);
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		500,
		global_d3d_device);

	local_fog_pass = pass;
	if (pass == 0)
		rasterizer_profile_begin(_rasterizer_profile_environment_fog_screen);
	if (rasterizer_environment_fog_screen_is_active())
	{
		struct rasterizer_environment_fog_screen_window *window =
			&windows[
				global_window_parameters.window_index];
		struct fog_screen const *screen = global_window_parameters.fog.screen;

		match_assert(
			"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
			514,
			local_fog_eye_density>0.0f);

		if (pass == 0)
		{
			real_matrix4x3 *previous_camera_matrix =
				&previous_camera_matrix[
					global_window_parameters.window_index];
			real_matrix4x3 wind_matrix = *global_identity4x3;
			real screen_constants[5][4];
			real_matrix4x3 matrix;
			real texture_transforms[MAXIMUM_ENVIRONMENT_FOG_SCREEN_LAYERS][8];
			real_vector3d vector;
			real layer_spacing;
			real inverse_depth;
			real aspect_ratio;
			real projection_scale;
			real cosine;
			real sine;
			short layer;

			{
			if (local_fog_screen_first_time)
			{
				short window_index;

				(void)bitmap_group_get(screen->map.index);
				for (window_index = 0; window_index < MAXIMUM_WINDOWS; window_index++)
				{
					csmemset(
						&windows[window_index],
						0,
						sizeof(struct rasterizer_environment_fog_screen_window));
					for (layer = 0; layer < screen->layer_count; layer++)
					{
						struct rasterizer_environment_fog_screen_layer *layer_state =
							&windows[window_index].
								layers[layer];

						layer_state->v = real_local_random();
						layer_state->u = real_local_random();
					}
					/* January copies the first matrix-sized camera bytes here verbatim. */
					csmemcpy(
						&previous_camera_matrix[
							window_index],
						&global_window_parameters.camera,
						sizeof(previous_camera_matrix[
							window_index]));
				}
				local_fog_screen_first_time = FALSE;
			}

			rasterizer_environment_fog_screen_wind_update(screen, &window->wind);
			rasterizer_environment_fog_screen_wind_get_vector(
				global_window_parameters.window_index,
				global_frame_parameters.dt,
				&vector);
			wind_matrix.position.x = vector.i;
			wind_matrix.position.y = vector.j;
			matrix4x3_inverse(previous_camera_matrix, &matrix);
			matrix4x3_multiply(&wind_matrix, &matrix, &matrix);
			matrix4x3_multiply(&global_window_parameters.frustum.world_to_view, &matrix, &matrix);
			csmemcpy(
				&previous_camera_matrix[
					global_window_parameters.window_index],
				&global_window_parameters.frustum.world_to_view,
				sizeof(real_matrix4x3));
			}

			layer_spacing = (screen->far_distance - screen->near_distance) / screen->layer_count;
			inverse_depth = 1.0f / (screen->far_distance - screen->near_distance);
			aspect_ratio = (real)(global_window_parameters.camera.viewport_bounds.y1 -
				global_window_parameters.camera.viewport_bounds.y0) /
				(real)(global_window_parameters.camera.viewport_bounds.x1 -
					global_window_parameters.camera.viewport_bounds.x0);
			projection_scale = screen->map_scale * 0.5f /
				(tan(global_window_parameters.camera.vertical_field_of_view * 0.5f) *
					screen->far_distance * aspect_ratio);

			screen_constants[0][0] = 2.0f / (global_window_parameters.camera.viewport_bounds.x1 -
				global_window_parameters.camera.viewport_bounds.x0);
			screen_constants[0][1] = 0.0f;
			screen_constants[0][2] = 0.0f;
			screen_constants[0][3] = -1.0f - 1.0f / (global_window_parameters.camera.viewport_bounds.x1 -
				global_window_parameters.camera.viewport_bounds.x0);
			screen_constants[1][0] = 0.0f;
			screen_constants[1][1] = -2.0f / (global_window_parameters.camera.viewport_bounds.y1 -
				global_window_parameters.camera.viewport_bounds.y0);
			screen_constants[1][2] = 0.0f;
			screen_constants[1][3] = 1.0f + 1.0f / (global_window_parameters.camera.viewport_bounds.y1 -
				global_window_parameters.camera.viewport_bounds.y0);
			screen_constants[2][0] = 0.0f;
			screen_constants[2][1] = 0.0f;
			screen_constants[2][2] = 0.0f;
			screen_constants[2][3] = 0.5f;
			screen_constants[3][0] = 0.0f;
			screen_constants[3][1] = 0.0f;
			screen_constants[3][2] = 0.0f;
			screen_constants[3][3] = 1.0f;
			screen_constants[4][0] = 0.0f;
			screen_constants[4][1] = 0.0f;
			screen_constants[4][2] = 0.0f;
			screen_constants[4][3] = 1.0f;

			vector.i = 1.0f;
			vector.j = 0.0f;
			vector.k = 0.0f;
			matrix4x3_transform_normal(&matrix, &vector, &vector);
			window->rotation += (real)atan2(vector.j, vector.i) *
				screen->rotation_multiplier;
			cosine = (real)cos(window->rotation);
			sine = (real)sin(window->rotation);

			if (screen->far_distance - screen->near_distance > 0.01f)
			{
				long offset;

				window->base_z -= screen->zoom_multiplier / layer_spacing * matrix.position.z;
				offset = fast_ftol((real)floor(window->base_z));
				if (offset > 0)
				{
					real u = real_local_random();
					real v = real_local_random();
					short index = (word)(window->animation_index - 1) % screen->layer_count;

					window->layers[index].u = v;
					window->layers[index].v = u;
				}
				else if (offset < 0)
				{
					real u = real_local_random();
					real v = real_local_random();
					short index = window->animation_index;

					window->layers[index].u = v;
					window->layers[index].v = u;
				}
				window->animation_index = (word)(window->animation_index - offset) %
					screen->layer_count;
				window->base_z -= (real)offset;
				if (!(window->base_z >= 0.0f && window->base_z < 1.0f))
				{
					error(
						_error_silent,
						"### ERROR fog_screen: base z failure (near=%f, far=%f, z=%f, offset=%d) -- tell Bernie!",
						screen->near_distance,
						screen->far_distance,
						window->base_z,
						offset);

					return;
				}
			}

			{
			real animation_times[MAXIMUM_ENVIRONMENT_FOG_SCREEN_LAYERS];
			real phase[MAXIMUM_ENVIRONMENT_FOG_SCREEN_LAYERS];

			phase[0] = 0.0f;
			phase[1] = 0.7135f;
			phase[2] = 0.3422f;
			phase[3] = 0.5798f;
			for (layer = 0; layer < screen->layer_count; layer++)
			{
				struct bitmap_group const *bitmap_group = bitmap_group_get(screen->map.index);

				match_assert(
					"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
					653,
					bitmap_group && bitmap_group->bitmaps.count>0);

				if (screen->animation_period != 0.0f)
				{
					short animation_index;
					real t = bitmap_group->bitmaps.count * phase[layer] +
						global_frame_parameters.game_time_sec / screen->animation_period;
					real animation_time = (real)PIN(t - floor(t), 0.0, 1.0);

					animation_times[layer] = animation_time;
					animation_index = (short)(fast_ftol((real)floor(t)) % bitmap_group->bitmaps.count);
					if (animation_index < 0)
					{
						if (!reported_bad_animation_index)
						{
							long game_time_bits;
							long animation_period_bits;
							long phase_bits;
							long time_bits;
							long animation_time_bits;

							csmemcpy(
								&game_time_bits,
								&global_frame_parameters.game_time_sec,
								sizeof(game_time_bits));
							csmemcpy(
								&animation_period_bits,
								&screen->animation_period,
								sizeof(animation_period_bits));
							csmemcpy(
								&phase_bits,
								&phase[layer],
								sizeof(phase_bits));
							csmemcpy(
								&time_bits,
								&t,
								sizeof(time_bits));
							csmemcpy(
								&animation_time_bits,
								&animation_times[layer],
								sizeof(animation_time_bits));
							error(
								_error_silent,
								"### ERROR fog screen animation index is invalid -- tell Bernie!!");
							error(
								_error_silent,
								"\tindex=%d",
								animation_index);
							error(
								_error_silent,
								"\ttime=%f[%x]",
								global_frame_parameters.game_time_sec,
								game_time_bits);
							error(
								_error_silent,
								"\tperiod=%f[%x]",
								screen->animation_period,
								animation_period_bits);
							error(
								_error_silent,
								"\tphase=%f[%x]",
								phase[layer],
								phase_bits);
							error(
								_error_silent,
								"\tt=%f[%x]",
								t,
								time_bits);
							error(
								_error_silent,
								"\tanimation_time=%f[%x]",
								animation_time,
								animation_time_bits);
							reported_bad_animation_index = TRUE;
						}
						animation_index = 0;
					}
					match_assert(
						"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
						682,
						animation_index>=0 && animation_index<bitmap_group->bitmaps.count);
					local_fog_screen_layer_bitmap_indices[layer] = animation_index;
				}
				else
				{
					animation_times[layer] = 0.0f;
					local_fog_screen_layer_bitmap_indices[layer] =
						(short)(layer % bitmap_group->bitmaps.count);
				}
			}

			for (layer = 0; layer < screen->layer_count; layer++)
			{
				short index = (word)(window->animation_index + layer) % screen->layer_count;
				real z = ((real)layer + window->base_z) * layer_spacing + screen->near_distance;
				real density = (real)pow(
					1.0 - pow(fabs((z - screen->near_distance) * inverse_depth * 2.0f - 1.0f), 3.0),
					2.0) * (local_fog_eye_density * screen->far_density);
				real scale = screen->map_scale / screen->far_distance * z;
				real_rgb_color *color = &local_fog_screen_layer_colors[layer];
				real_point3d point;

				point.x = 0.0f;
				point.y = 0.0f;
				point.z = -z;
				matrix4x3_transform_point(&matrix, &point, &point);
				window->layers[index].u -= (point.x * cosine + point.y * sine) *
					screen->strafing_multiplier * projection_scale;
				window->layers[index].v -= (point.y * cosine - point.x * sine) *
					screen->strafing_multiplier * projection_scale;
				if (screen->far_density != 0.0f)
				{
					real inverse_time = 1.0f - animation_times[index];

					color->red = inverse_time * inverse_time * density;
					color->green = 2.0f * animation_times[index] * inverse_time * density;
					color->blue = animation_times[index] * animation_times[index] * density;
				}
				else
				{
					color->red = 0.0f;
					color->green = density;
					color->blue = 0.0f;
				}
				texture_transforms[layer][0] = scale * cosine * 0.5f;
				texture_transforms[layer][1] = scale * sine * aspect_ratio * 0.5f;
				texture_transforms[layer][2] = 0.0f;
				texture_transforms[layer][3] = window->layers[index].u;
				texture_transforms[layer][4] = scale * sine * -0.5f;
				texture_transforms[layer][5] = scale * cosine * aspect_ratio * 0.5f;
				texture_transforms[layer][6] = 0.0f;
				texture_transforms[layer][7] = window->layers[index].v;
			}

			}

			IDirect3DDevice8_SetVertexShaderConstant(
				global_d3d_device,
				-81,
				texture_transforms,
				8);
			IDirect3DDevice8_SetVertexShaderConstant(
				global_d3d_device,
				-68,
				screen_constants,
				5);

			if (screen->near_density == screen->far_density)
			{
				local_environment_fog_screen_flag = FALSE;
				local_environment_fog_screen_model_flag = FALSE;

				return;
			}
			local_environment_fog_screen_flag = !TEST_FLAG(
				global_window_parameters.fog.screen->flags,
				_fog_screen_no_environment_multipass_bit);
			local_environment_fog_screen_model_flag = !TEST_FLAG(
				global_window_parameters.fog.screen->flags,
				_fog_screen_no_model_multipass_bit) &&
				opaque_model_count > 0;
		}
		if (local_environment_fog_screen_flag || local_environment_fog_screen_model_flag)
		{
			boolean success;
			boolean clear_z_buffer;
			real vsh_constants__texscale[VSH_CONSTANTS__TEXSCALE_COUNT][4];

			if (pass == 0)
			{
				if (TEST_FLAG(screen->flags, _fog_screen_no_environment_multipass_bit))
				{
					clear_z_buffer = !TEST_FLAG(
						screen->flags,
						_fog_screen_no_model_multipass_bit);
				}
				else
				{
					clear_z_buffer = (TEST_FLAG(
						screen->flags,
						_fog_screen_no_model_multipass_bit) &&
						opaque_model_count > 0) ||
						(rasterizer_water_get_visibility_for_window() &&
							rasterizer_debug_options.draw_water);
				}
			}
			else
			{
				clear_z_buffer = FALSE;
			}

			success = IDirect3DDevice8_Clear(
				global_d3d_device,
				0,
				NULL,
				D3DCLEAR_TARGET | (clear_z_buffer ? D3DCLEAR_ZBUFFER : 0),
				0,
				1.0f,
				0) >= 0;
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_CULLMODE, D3DCULL_CCW);
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_COLORWRITEENABLE,
				D3DCOLORWRITEENABLE_ALPHA);
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ALPHABLENDENABLE, FALSE);
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ALPHATESTENABLE, FALSE);
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZENABLE, TRUE);
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZFUNC,
				pass != 0 ? D3DCMP_EQUAL : D3DCMP_LESSEQUAL);
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZWRITEENABLE, pass == 0);
			IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZBIAS, 0);

			if (pass == 0)
			{
				real inverse_depth = 1.0f /
					(screen->far_distance - screen->near_distance);

				vsh_constants__texscale[1][0] = 0.0f;
				vsh_constants__texscale[1][1] = 0.0f;
				vsh_constants__texscale[1][2] = 0.0f;
				vsh_constants__texscale[1][3] = 0.0f;
				vsh_constants__texscale[2][0] = 0.0f;
				vsh_constants__texscale[2][1] = 0.0f;
				vsh_constants__texscale[2][2] = 0.0f;
				vsh_constants__texscale[2][3] = 0.0f;
				vsh_constants__texscale[0][0] =
					global_window_parameters.camera.forward.i * inverse_depth;
				vsh_constants__texscale[0][1] =
					global_window_parameters.camera.forward.j * inverse_depth;
				vsh_constants__texscale[0][2] =
					global_window_parameters.camera.forward.k * inverse_depth;
				vsh_constants__texscale[0][3] = -((
					global_window_parameters.camera.position.x *
						global_window_parameters.camera.forward.i +
					global_window_parameters.camera.position.y *
						global_window_parameters.camera.forward.j +
					global_window_parameters.camera.position.z *
						global_window_parameters.camera.forward.k +
					screen->near_distance) * inverse_depth);
				success = IDirect3DDevice8_SetVertexShaderConstant(
					global_d3d_device,
					VSH_CONSTANTS__TEXSCALE_OFFSET,
					vsh_constants__texscale,
					1) >= 0;
			}

			csmemset(&pixel_shader, 0, sizeof(pixel_shader));
			if (TEST_FLAG(global_window_parameters.fog.screen->flags,
				_fog_screen_no_texture_bit))
			{
				pixel_shader.combiner_count = 1;
				pixel_shader.final_combiner_inputs_efg = 0x3300;
			}
			else
			{
				real alpha;

				rasterizer_set_texture_direct(
					0,
					global_rasterizer_data->planar_fog_density.index,
					0);
				IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_ADDRESSU, D3DTADDRESS_CLAMP);
				IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_ADDRESSV, D3DTADDRESS_CLAMP);
				IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_MAGFILTER, D3DTEXF_LINEAR);
				IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_MINFILTER, D3DTEXF_LINEAR);
				IDirect3DDevice8_SetTextureStageState(global_d3d_device, 0, D3DTSS_MIPFILTER, D3DTEXF_LINEAR);
				match_assert(
					"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
					856,
					screen->far_density!=0.0f);
				pixel_shader.texture_modes = 1;
				pixel_shader.combiner_count = 1;
				alpha = screen->near_density / screen->far_density;
				pixel_shader.constant_0[0] = real_alpha_to_pixel32(alpha);
				pixel_shader.alpha_inputs[0] = 0x28110820;
				pixel_shader.alpha_outputs[0] = 0xC00;
				pixel_shader.final_combiner_inputs_efg = 0x3C00;
			}
			rasterizer_set_pixel_shader(&pixel_shader);

			if (local_environment_fog_screen_model_flag)
			{
				short group_index;

				for (group_index = 0;
					group_index < opaque_model_count;
					group_index++)
				{
					struct transparent_geometry_group *group =
						&opaque_model_submit_parameters[group_index];
					struct render_skinning skinning;

					if (group->shader->base.type == _shader_type_transparent_chicago &&
						!TEST_FLAG(
							((struct shader_transparent_chicago_definition *)
								shader_get_and_verify_type(
									group->shader,
									_shader_type_transparent_chicago))->flags,
							_shader_transparent_chicago_no_fog_bit))
					{
						struct shader_transparent_chicago_definition const *chicago =
							(struct shader_transparent_chicago_definition *)group->shader;

						{
							D3DDevice_SetRenderState_PSTextureModes(0x21);
							IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_ALPHAKILL, D3DTALPHAKILL_ENABLE);
							rasterizer_set_texture(
								1,
								0,
								1,
								chicago->map.index,
								group->shader_permutation_index);
							IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_ADDRESSU, D3DTADDRESS_WRAP);
							IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_ADDRESSV, D3DTADDRESS_WRAP);
							IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_MAGFILTER, D3DTEXF_LINEAR);
							IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_MINFILTER, D3DTEXF_LINEAR);
							IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_MIPFILTER, D3DTEXF_LINEAR);
							vsh_constants__texscale[1][0] = chicago->map_u_scale * group->model_base_map_scale.i;
							vsh_constants__texscale[1][1] = 0.0f;
							vsh_constants__texscale[1][2] = 0.0f;
							vsh_constants__texscale[1][3] = 0.0f;
							vsh_constants__texscale[2][0] = 0.0f;
							vsh_constants__texscale[2][1] = chicago->map_v_scale * group->model_base_map_scale.j;
							vsh_constants__texscale[2][2] = 0.0f;
							vsh_constants__texscale[2][3] = 0.0f;
							if (IDirect3DDevice8_SetVertexShaderConstant(
								global_d3d_device,
								VSH_CONSTANTS__TEXSCALE_OFFSET + 1,
								vsh_constants__texscale[1],
								VSH_CONSTANTS__TEXSCALE_COUNT - 1) >= 0 && success)
							{
								success = TRUE;
							}
							else
							{
								success = FALSE;
								rasterizer_error(
									0,
									"IDirect3DDevice8_SetVertexShaderConstant(global_d3d_device, VSH_CONSTANTS__TEXSCALE_OFFSET+1, vsh_constants__texscale_1, VSH_CONSTANTS__TEXSCALE_COUNT-1)");
							}
						}
					}
					else if (group->shader->base.type == _shader_type_transparent_chicago ||
						group->shader->base.type == _shader_type_environment ||
						group->shader->base.type == _shader_type_transparent_generic)
					{
						D3DDevice_SetRenderState_PSTextureModes(1);
						IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_ALPHAKILL, D3DTALPHAKILL_DISABLE);
					}
					rasterizer_set_vertex_shader_permutation(
						5,
						rasterizer_transparent_geometry_get_primary_vertex_type(group),
						FALSE);
					if (group->node_matrices && group->node_matrix_count)
					{
						skinning.node_matrices = group->node_matrices;
						skinning.node_matrix_count = group->node_matrix_count;
					}
					else
					{
						skinning.node_matrices = global_identity4x3;
						skinning.node_matrix_count = 1;
					}
					rasterizer_set_model_skinning(&skinning);
					if (success)
					{
						rasterizer_transparent_geometry_group_draw__internal(group, FALSE);
						if (rasterizer_debug_options.statistics_mode ==
							_rasterizer_statistics_mode_enabled)
						{
							rasterizer_frame_statistics.
								environment_fog_screen_static_draw_count++;
							rasterizer_frame_statistics.
								environment_fog_screen_static_triangle_count +=
									group->triangle_count;
							rasterizer_frame_statistics.
								environment_fog_screen_static_vertex_count +=
									rasterizer_frame_statistics_count_static_vertices(
										group->triangle_buffer,
										group->vertex_buffer);
						}
					}
				}
			}
			IDirect3DDevice8_SetTextureStageState(global_d3d_device, 1, D3DTSS_ALPHAKILL, D3DTALPHAKILL_DISABLE);
			if (!success)
			{
				error(
					_error_silent,
					"### ERROR rasterizer_environment_fog_screen_begin failed");
			}
		}
	}

	return;
}

void _rasterizer_environment_fog_screen_draw(
	struct shader const *shader,
	short shader_permutation_index,
	long dynamic_triangle_buffer_index,
	long first_triangle_index,
	long triangle_count,
	struct vertex_buffer const *vertex_buffer)
{
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		988,
		global_d3d_device);
	if (rasterizer_environment_fog_screen_is_active())
	{
		match_assert(
			"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
			992,
			local_fog_pass==0 || local_fog_pass==1);
		if (local_environment_fog_screen_flag)
		{
			match_assert(
				"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
				996,
				global_window_parameters.fog.screen);
			match_assert(
				"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
				997,
				global_window_parameters.window_index>=0 &&
					global_window_parameters.window_index<MAXIMUM_WINDOWS);

			rasterizer_set_vertex_shader_permutation(
				_rasterizer_vertex_shader_environment_fog_screen,
				vertex_buffer->type,
				shader_get_vertex_shader_permutation(shader));
			rasterizer_draw_dynamic_triangles_static_vertices(
				dynamic_triangle_buffer_index,
				first_triangle_index,
				triangle_count,
				vertex_buffer);
			if (rasterizer_debug_options.statistics_mode ==
				_rasterizer_statistics_mode_enabled)
			{
				rasterizer_frame_statistics.environment_fog_screen_dynamic_draw_count++;
				rasterizer_frame_statistics.environment_fog_screen_dynamic_triangle_count +=
					triangle_count;
				rasterizer_frame_statistics.environment_fog_screen_dynamic_vertex_count +=
					rasterizer_frame_statistics_count_dynamic_vertices(
						dynamic_triangle_buffer_index,
						first_triangle_index,
						triangle_count);
			}
		}
	}

	return;
}

void _rasterizer_environment_fog_screen_end(
	void)
{
	match_assert(
		"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
		1036,
		global_d3d_device);
	if (rasterizer_environment_fog_screen_is_active())
	{
		struct fog_screen const *screen = global_window_parameters.fog.screen;
		struct rasterizer_environment_fog_screen_window *window =
			&windows[
				global_window_parameters.window_index];
		boolean fog_screen_drawn = local_environment_fog_screen_flag ||
			local_environment_fog_screen_model_flag;
		short layer;

		match_assert(
			"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
			1045,
			local_fog_pass==0 || local_fog_pass==1);
		match_assert(
			"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
			1047,
			global_window_parameters.fog.screen);
		match_assert(
			"c:\\halo\\SOURCE\\rasterizer\\xbox\\rasterizer_xbox_environment_fog.c",
			1048,
			global_window_parameters.window_index>=0 &&
				global_window_parameters.window_index<MAXIMUM_WINDOWS);

		for (layer = 0; layer < screen->layer_count; layer++)
		{
			word animation_index = window->animation_index + layer;
			short layer_index = animation_index % screen->layer_count;

			rasterizer_set_texture_direct(
				layer,
				screen->map.index,
				local_fog_screen_layer_bitmap_indices[layer_index]);
			IDirect3DDevice8_SetTextureStageState(global_d3d_device, layer, D3DTSS_ADDRESSU, D3DTADDRESS_WRAP);
			IDirect3DDevice8_SetTextureStageState(global_d3d_device, layer, D3DTSS_ADDRESSV, D3DTADDRESS_WRAP);
			IDirect3DDevice8_SetTextureStageState(global_d3d_device, layer, D3DTSS_MAGFILTER, D3DTEXF_LINEAR);
			IDirect3DDevice8_SetTextureStageState(global_d3d_device, layer, D3DTSS_MINFILTER, D3DTEXF_LINEAR);
			IDirect3DDevice8_SetTextureStageState(global_d3d_device, layer, D3DTSS_MIPFILTER, D3DTEXF_LINEAR);
		}

		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_CULLMODE, D3DCULL_CCW);
		IDirect3DDevice8_SetRenderState(
			global_d3d_device,
			D3DRS_COLORWRITEENABLE,
			local_fog_pass == 0 && fog_screen_drawn
				? D3DCOLORWRITEENABLE_ALPHA
				: D3DCOLORWRITEENABLE_RED | D3DCOLORWRITEENABLE_GREEN | D3DCOLORWRITEENABLE_BLUE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ALPHABLENDENABLE, TRUE);
		IDirect3DDevice8_SetRenderState(
			global_d3d_device,
			D3DRS_SRCBLEND,
			fog_screen_drawn ? D3DBLEND_INVDESTALPHA : D3DBLEND_ONE);
		IDirect3DDevice8_SetRenderState(
			global_d3d_device,
			D3DRS_DESTBLEND,
			fog_screen_drawn ? D3DBLEND_ONE : D3DBLEND_SRCALPHA);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_BLENDOP, D3DBLENDOP_ADD);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ALPHATESTENABLE, FALSE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZENABLE, FALSE);
		IDirect3DDevice8_SetRenderState(global_d3d_device, D3DRS_ZBIAS, 0);

		rasterizer_set_vertex_shader_permutation(
			_rasterizer_vertex_shader_screen_effect,
			_rasterizer_vertex_type_dynamic_screen,
			FALSE);

		csmemset(&pixel_shader, 0, sizeof(pixel_shader));
		pixel_shader.texture_modes = PS_TEXTUREMODES(
			PS_TEXTUREMODES_PROJECT2D,
			screen->layer_count > 1 ? PS_TEXTUREMODES_PROJECT2D : PS_TEXTUREMODES_NONE,
			screen->layer_count > 2 ? PS_TEXTUREMODES_PROJECT2D : PS_TEXTUREMODES_NONE,
			screen->layer_count > 3 ? PS_TEXTUREMODES_PROJECT2D : PS_TEXTUREMODES_NONE);
		pixel_shader.combiner_count = PS_COMBINERCOUNT(
			4,
			PS_COMBINERCOUNT_UNIQUE_C0 | PS_COMBINERCOUNT_UNIQUE_C1);
		pixel_shader.constant_0[0] = real_rgb_color_to_pixel32(&local_fog_screen_layer_colors[0]);
		pixel_shader.constant_1[0] = real_rgb_color_to_pixel32(&local_fog_screen_layer_colors[1]);
		pixel_shader.rgb_inputs[0] = PS_COMBINERINPUTS(
			PS_REGISTER_T0,
			PS_REGISTER_C0,
			PS_REGISTER_T1,
			PS_REGISTER_C1);
		pixel_shader.rgb_outputs[0] = PS_COMBINEROUTPUTS(
			PS_REGISTER_T0,
			PS_REGISTER_T1,
			PS_REGISTER_DISCARD,
			PS_COMBINEROUTPUT_AB_DOT_PRODUCT | PS_COMBINEROUTPUT_CD_DOT_PRODUCT);
		pixel_shader.constant_0[1] = real_rgb_color_to_pixel32(&local_fog_screen_layer_colors[2]);
		pixel_shader.constant_1[1] = real_rgb_color_to_pixel32(&local_fog_screen_layer_colors[3]);
		pixel_shader.alpha_inputs[1] = PS_COMBINERINPUTS(
			PS_REGISTER_T0 | PS_INPUTMAPPING_UNSIGNED_INVERT,
			screen->layer_count > 1
				? PS_REGISTER_T1 | PS_INPUTMAPPING_UNSIGNED_INVERT
				: PS_REGISTER_ONE,
			PS_REGISTER_ZERO,
			PS_REGISTER_ZERO);
		pixel_shader.alpha_outputs[1] = PS_COMBINEROUTPUTS(
			PS_REGISTER_R0,
			PS_REGISTER_DISCARD,
			PS_REGISTER_DISCARD,
			PS_COMBINEROUTPUT_IDENTITY);
		pixel_shader.rgb_inputs[1] = PS_COMBINERINPUTS(
			PS_REGISTER_T2,
			PS_REGISTER_C0,
			PS_REGISTER_T3,
			PS_REGISTER_C1);
		pixel_shader.rgb_outputs[1] = PS_COMBINEROUTPUTS(
			PS_REGISTER_T2,
			PS_REGISTER_T3,
			PS_REGISTER_DISCARD,
			PS_COMBINEROUTPUT_AB_DOT_PRODUCT | PS_COMBINEROUTPUT_CD_DOT_PRODUCT);
		pixel_shader.alpha_inputs[2] = PS_COMBINERINPUTS(
			screen->layer_count > 2
				? PS_REGISTER_T2 | PS_INPUTMAPPING_UNSIGNED_INVERT
				: PS_REGISTER_ONE,
			screen->layer_count > 3
				? PS_REGISTER_T3 | PS_INPUTMAPPING_UNSIGNED_INVERT
				: PS_REGISTER_ONE,
			PS_REGISTER_ZERO,
			PS_REGISTER_ZERO);
		pixel_shader.alpha_outputs[2] = PS_COMBINEROUTPUTS(
			PS_REGISTER_R1,
			PS_REGISTER_DISCARD,
			PS_REGISTER_DISCARD,
			PS_COMBINEROUTPUT_IDENTITY);
		pixel_shader.rgb_inputs[2] = PS_COMBINERINPUTS(
			screen->layer_count > 2
				? PS_REGISTER_T2 | PS_INPUTMAPPING_UNSIGNED_INVERT
				: PS_REGISTER_ONE,
			screen->layer_count > 3 ? PS_REGISTER_T3 : PS_REGISTER_ZERO,
			screen->layer_count > 2 ? PS_REGISTER_T2 : PS_REGISTER_ZERO,
			PS_REGISTER_ONE);
		pixel_shader.rgb_outputs[2] = PS_COMBINEROUTPUTS(
			PS_REGISTER_DISCARD,
			PS_REGISTER_DISCARD,
			PS_REGISTER_R0,
			PS_COMBINEROUTPUT_IDENTITY);
		pixel_shader.alpha_inputs[3] = PS_COMBINERINPUTS(
			PS_REGISTER_R0 | PS_CHANNEL_ALPHA,
			PS_REGISTER_R1 | PS_CHANNEL_ALPHA,
			PS_REGISTER_ZERO,
			PS_REGISTER_ZERO);
		pixel_shader.alpha_outputs[3] = PS_COMBINEROUTPUTS(
			PS_REGISTER_R0,
			PS_REGISTER_DISCARD,
			PS_REGISTER_DISCARD,
			PS_COMBINEROUTPUT_IDENTITY);
		pixel_shader.rgb_inputs[3] = PS_COMBINERINPUTS(
			screen->layer_count > 1
				? PS_REGISTER_T1 | PS_INPUTMAPPING_UNSIGNED_INVERT
				: PS_REGISTER_ONE,
			PS_REGISTER_R0,
			screen->layer_count > 1 ? PS_REGISTER_T1 : PS_REGISTER_ZERO,
			PS_REGISTER_ONE);
		pixel_shader.rgb_outputs[3] = PS_COMBINEROUTPUTS(
			PS_REGISTER_DISCARD,
			PS_REGISTER_DISCARD,
			PS_REGISTER_R0,
			PS_COMBINEROUTPUT_IDENTITY);
		if (screen->color)
		{
			pixel_shader.final_combiner_constant_0 = screen->color;
		}
		else
		{
			pixel_shader.final_combiner_constant_0 =
				real_rgb_color_to_pixel32(&global_window_parameters.fog.planar_color);
		}
		pixel_shader.final_combiner_inputs_abcd = PS_COMBINERINPUTS(
			PS_REGISTER_T0,
			PS_REGISTER_C0,
			PS_REGISTER_EF_PROD,
			PS_REGISTER_ZERO);
		pixel_shader.final_combiner_inputs_efg = PS_COMBINERINPUTS(
			PS_REGISTER_R0,
			PS_REGISTER_C0,
			PS_REGISTER_R0 | PS_CHANNEL_ALPHA,
			0);
		rasterizer_set_pixel_shader(&pixel_shader);

		IDirect3DDevice8_Begin(global_d3d_device, D3DPT_TRIANGLEFAN);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, -1, 1);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, -1, 1);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, 1, 1);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, 1, 1);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, 1, -1);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, 1, -1);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, -1, -1);
		IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, -1, -1);
		IDirect3DDevice8_End(global_d3d_device);

		if (local_fog_pass == 0 && fog_screen_drawn)
		{
			IDirect3DDevice8_SetRenderState(
				global_d3d_device,
				D3DRS_COLORWRITEENABLE,
				D3DCOLORWRITEENABLE_RED | D3DCOLORWRITEENABLE_GREEN | D3DCOLORWRITEENABLE_BLUE);
			IDirect3DDevice8_SetRenderState(
				global_d3d_device,
				D3DRS_SRCBLEND,
				D3DBLEND_INVDESTALPHA);
			IDirect3DDevice8_SetRenderState(
				global_d3d_device,
				D3DRS_DESTBLEND,
				D3DBLEND_ONE);

			csmemset(&pixel_shader, 0, sizeof(pixel_shader));
			pixel_shader.combiner_count = PS_COMBINERCOUNT(1, 0);
			rasterizer_set_pixel_shader(&pixel_shader);

			IDirect3DDevice8_Begin(global_d3d_device, D3DPT_TRIANGLEFAN);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, -1, 1);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, -1, 1);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, 1, 1);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, 1, 1);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, 1, -1);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, 1, -1);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_SPECULAR, -1, -1);
			IDirect3DDevice8_SetVertexData2s(global_d3d_device, D3DVSDE_POSITION, -1, -1);
			IDirect3DDevice8_End(global_d3d_device);
		}
	}
	if (local_fog_pass != 0)
		rasterizer_profile_end(_rasterizer_profile_environment_fog_screen);

	return;
}
